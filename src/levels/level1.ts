// 第一关 · 转一下,渠就接上了
//
// 只教三件事:**转相机**、**引水**、**走过去**。别的一概不做。
//
// 流程:
//   1. 兽从出生点走到泉眼               —— 走
//   2. 按空格引水,水流进渠里,停住      —— 引水,并且看见渠断了一截
//   3. 转相机,断开的那截接上了大池      —— 转相机(45° → 135°)
//   4. 再按空格,渠灌满,大池填满,过关
//
// 第 2 步那个「水停在渠里、末端悬空」不是 bug,是规格要求的可见状态。玩家在
// 那一刻会自己去找办法,而画面上唯一还没试过的东西就是方向键。

import type { Layout } from "../iso.ts";
import type { Level } from "../rules.ts";

export const level1: Level = {
  name: "转一下,渠就接上了",

  // `on` 是这个池子嵌在哪块砖里。声明出来,而不是让渲染器去比坐标猜 ——
  // 「哪块砖是池子的底」和连通一样,是数据说了算的事。
  pools: [
    { id: "spring", on: "springDeck" },
    { id: "grandBasin", on: "basinDeck", isFinal: true, grand: true },
  ],

  // 一条渠,一个断口。这一关只有它。
  channels: [{ id: "aqueduct", ends: ["spring", "grandBasin"] }],

  // springDeck / basinDeck 是池子坐进去的那块砖。它们不参与任何连通声明 ——
  // 兽走的是 spring 这个池子本身(站在池子上引水),砖只是池子的底。
  platforms: [
    { id: "birth" },
    { id: "walkway" },
    { id: "springDeck" },
    { id: "basinDeck" },
  ],

  tapPoints: [],
  parts: [],

  waterLinks: [
    // 上游口一直坐在泉眼上,任何角度都接着。
    { from: "spring", to: "aqueduct", when: {} },
    // 下游口只在 135° 落到大池边沿。另外三个角度它悬在空中 ——
    // 水流进去就停住,末端悬空。
    { from: "aqueduct", to: "grandBasin", when: { camera: 135 } },
  ],

  walkLinks: [
    { between: ["birth", "walkway"], when: {} },
    { between: ["walkway", "spring"], when: {} },
    // 灌满之后,渠面就是路,兽可以踩着走到大池 —— 但仍然要那个角度看得通。
    { between: ["spring", "aqueduct"], when: { camera: 135 } },
    { between: ["aqueduct", "grandBasin"], when: { camera: 135 } },
  ],

  beastAt: "birth",

  // 开局 45°,右键一下就是 135° —— 「转一下」就是一下。
  opens: { camera: 45, turns: {} },
};

/**
 * 摆放。
 *
 * 渠的下游口 (1,1,4) 与大池 (0,2,5) 差一个 (-1,1,1) —— 那**就是** 135° 的
 * 隐身方向本身。每个相机角度的隐身方向都不一样,所以这个差值只在 135° 让两者
 * 落到同一像素;另外三个角度差 1.63,断得清清楚楚。
 *
 * 用反向而不是正向,是为了让大池落在渠口**背后** —— 见下面 grandBasin 的注释。
 *
 * 渠为什么跨两格:两个池心只隔一格时,两个半径 0.4 的水面之间只剩 0.2,
 * 「不重叠地接上」的渠就只能是 0.2 长的一个疙瘩,半满状态更是看不见。
 * 隔两格,渠从池沿画到池沿正好 1.2,断口那半截也才有得看。
 */
export const level1Layout: Layout = {
  pivots: {},
  ports: {
    // 上面这条路都在 y=1:泉眼和渠架在空中,大池在下面一层。
    birth: { at: [1, 1, 0] },
    walkway: { at: [1, 1, 1] },
    spring: { at: [1, 1, 2] },
    // 和 spring 同格:池子就嵌在这块砖里,不是挨着它。
    springDeck: { at: [1, 1, 2] },
    // 逻辑锚点是两端的**池心**;画出来的槽从池沿起、到池沿止(见 scene.ts
    // 的 channel())。跨两格,所以看得见的槽有 1.2 长。
    aqueduct: { from: [1, 1, 2], to: [1, 1, 4] },
    // 大池在渠口的**近端**。
    //
    // 隐身方向就是视线方向,所以屏幕上重合的两个东西必然一前一后,而「哪个在
    // 前」是这里唯一能选的东西 —— 沉多少、抬多高都改不了它。
    //
    // 一度放在远端(渠口在前、大池在后),理由是当时大池落在近端会把整条渠
    // 盖没,「接上了」根本看不见。那个理由随渠变长而失效了:渠当时只有 0.6,
    // 现在有 1.2,大池挡掉的是最外面的一截,不是整条。而放回近端换来的是
    // 作者要的那个读法 —— 池沿和水面在前,渠从它底下接进去,像渠真的钻进了
    // 池壁,而不是一根棍子搭在池口上。
    //
    // 附带一条:大池因此比泉眼**高**(y=2 对 y=1)。规格里幼发拉底河是爬上塔、
    // 最后灌满顶上的大蓄水池;而规则 2 管的是**画面上**谁低,画面上它就在渠口
    // 的下游端 —— 三维里更高、画面上更低,这正是这个游戏的错觉本身。
    grandBasin: { at: [0, 2, 5] },
    basinDeck: { at: [0, 2, 5] },
  },
};
